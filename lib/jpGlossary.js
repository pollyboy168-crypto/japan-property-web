// 🈁 日文不動產用語 → 繁體中文 對照表
//
// **為什麼標題不用機器翻譯？**
// 健美家的標題是高度格式化的短句，塞滿了日文不動產術語與價格數字，
// Google Translate 在這種輸入上錯得很難看，實測踩到的坑：
//   「45290万円」→「4,529 億天」（價格整個被改掉，這是會誤導買家的錯誤）
//   「健美家」  →「Kenbi-ya」  （公司名被音譯）
//   「満想5.28％」→「滿意度5.28%」（收益率被講成滿意度）
// 標題會直接出現在物件卡與搜尋結果，價格翻錯的代價遠高於翻得生硬，
// 所以標題改用這份「查表取代」——結果可預測、數字絕對不會被動到。
//
// 物件說明（description）是長篇自由文章，查表撐不住，那邊仍然用機器
// 翻譯，但譯完會再過一次這份表把術語校正回來。
// ----------------------------------------------------------------

