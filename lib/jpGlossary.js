// 長詞優先，否則「築」會先把「新築／年築」吃掉，變成「新年建」這種怪字。
// 在模組載入時排一次就好，不要每次呼叫都排。
const SORTED = [...GLOSSARY].sort((a, b) => b[0].length - a[0].length);

export function jpToZh(text) {
  if (!text) return text;
  let out = text;
  for (const [ja, zh] of SORTED) out = out.split(ja).join(zh);
  // 全形符號整理成台灣讀者習慣的寫法
  return out.replace(/／/g, '/').replace(/　/g, ' ');
}

// 還有沒有假名殘留？用來判斷查表夠不夠、要不要退回機器翻譯。
// （只看假名，不看漢字——漢字中日共用，出現漢字不代表沒翻到。）
export function hasKana(text) {
  return /[぀-ゟ゠-ヿ]/.test(text || '');
}
